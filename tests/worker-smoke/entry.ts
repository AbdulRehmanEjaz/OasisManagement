// Local runtime test only. This entry is never part of the deployed application.
import { checkPin, hashPin } from "../../src/lib/pin-crypto";
import { localPins } from "../../src/worker/local-pins";
import { processPhoto } from "../../src/worker/photo-processing";
import { createClient } from "@supabase/supabase-js";
import { createServerClient } from "@supabase/ssr";

export default {
  async fetch() {
    try {
      const assert = (ok: unknown, label: string) => {
        if (!ok) throw new Error(label);
      };
      // Known vector generated with Node 24's scryptSync defaults.
      assert(checkPin("worker-test-pin", "worker-test-salt:2f8f8802a78fcdf997ddf9627d3da27f71c09c9d4267458ec4aae17d0d6c2d29"), "Node scrypt hash compatibility");
      const hash = hashPin("worker-test-pin");
      assert(checkPin("worker-test-pin", hash) && !checkPin("wrong-pin", hash), "PIN hash round trip");
      let blocked = false;
      try { localPins(); } catch { blocked = true; }
      assert(blocked, "SQLite fallback must be disabled on Workers");

      // Exercise both actual Supabase packages with a fixture transport.
      let calls = 0;
      const transport: typeof fetch = async (input, options) => {
        const request = new Request(input, options);
        assert(request.url.includes("/rest/v1/"), "Supabase request URL");
        assert(request.headers.has("apikey"), "Supabase API key header");
        calls++;
        return Response.json([{ id: "fixture-report" }]);
      };
      const config = { global: { fetch: transport }, auth: { persistSession: false, autoRefreshToken: false } };
      const clients = [
        createClient("https://fixture.supabase.co", "fixture-key", config),
        createServerClient("https://fixture.supabase.co", "fixture-key", {
          ...config, cookies: { getAll: () => [], setAll: () => {} },
        }),
      ];
      for (const client of clients) {
        const result = await client.from("reports").select("id");
        assert(!result.error && result.data?.[0].id === "fixture-report", "Supabase response parsing");
      }
      assert(calls === 2, "Supabase transports executed");

      // Tiny PNG generated by sharp in Node, converted by the actual Images binding.
      const png = Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAIAAAACCAIAAAD91JpzAAAACXBIWXMAAAPoAAAD6AG1e1JrAAAAEUlEQVQImWMQz3AWz3BmgFAAFJYDCQJ1g9cAAAAASUVORK5CYII=", "base64");
      const jpeg = await processPhoto(png);
      assert(jpeg[0] === 0xff && jpeg[1] === 0xd8, "Cloudflare Images JPEG conversion");
      let invalidBlocked = false;
      try { await processPhoto(Buffer.from("not an image")); } catch { invalidBlocked = true; }
      assert(invalidBlocked, "Malformed image rejection");

      // ImgBB and Resend use these standard request encodings, with no native SDK.
      const form = new FormData(); form.set("key", "fixture"); form.set("image", jpeg.toString("base64"));
      const upload = new Request("https://api.imgbb.com/1/upload", { method: "POST", body: form });
      assert((await upload.formData()).get("image") === jpeg.toString("base64"), "ImgBB multipart encoding");
      const email = new Request("https://api.resend.com/emails", {
        method: "POST", headers: { Authorization: "Bearer fixture", "Content-Type": "application/json" },
        body: JSON.stringify({ subject: "fixture" }), signal: AbortSignal.timeout(1000),
      });
      assert((await email.json() as { subject: string }).subject === "fixture", "Resend JSON encoding");
      return Response.json({ scrypt: true, sqliteBlocked: true, supabasePackages: true,
        photoConversion: true, invalidPhotoBlocked: true, httpEncodings: true });
    } catch (error) {
      return Response.json({ error: (error as Error).message }, { status: 500 });
    }
  },
};
